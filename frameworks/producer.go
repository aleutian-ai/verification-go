package frameworks

import (
	"crypto/sha512"
	"encoding/hex"
	"fmt"
)

// FrameworkBundleEntry is the producer-facing description of how a
// compliance bundle should embed its framework slice.
//
// # Description
//
// The bundle producer (export_bundle_job_01c_finalize_stage) calls
// PinForBundle to get this struct, then:
//
//  1. Writes Contents to the bundle ZIP at Path.
//  2. Records {Path, SHA512Hex, SizeBytes} in manifest.files[] for
//     manifest_root coverage.
//  3. Sets manifest.framework_version = string(VersionID).
//
// All four steps together satisfy CV-02's self-containment contract:
// the bundle ships its own framework slice, the manifest pins the
// version, the verifier reads from the bundle (not from the SDK's
// embedded registry).
type FrameworkBundleEntry struct {
	// Path is the conventional location for the controls.json inside
	// the bundle ZIP: "frameworks/<framework_version>/controls.json".
	Path string

	// Contents is the byte-stable on-wire encoding of the framework
	// (canonical JSON with self-attestation hash populated).
	Contents []byte

	// SHA512Hex is the lowercase-hex SHA-512 of Contents, for the
	// manifest.files[] entry. This is the file-level hash, NOT the
	// framework's self-attestation hash. (The self-attestation hash
	// lives inside Contents as controls_sha512_hex; the manifest's
	// file hash covers the entire JSON bytes including that field.)
	SHA512Hex string

	// SizeBytes is len(Contents). Mirrors manifest.files[] schema.
	SizeBytes int64

	// VersionID is what producer code writes into
	// manifest.framework_version.
	VersionID VersionID
}

// PinForBundle resolves Latest[id] and returns the bytes + metadata
// the producer needs to embed the framework slice into a compliance
// bundle.
//
// # Description
//
// Producer flow (illustrative):
//
//	entry, err := frameworks.PinForBundle(req.Framework)
//	if err != nil { return err }
//	zipWriter.Add(entry.Path, entry.Contents)
//	manifest.Files = append(manifest.Files, ManifestFile{
//	    Path:      entry.Path,
//	    SHA512Hex: entry.SHA512Hex,
//	    SizeBytes: entry.SizeBytes,
//	})
//	manifest.FrameworkVersion = string(entry.VersionID)
//
// # Inputs
//
//   - id: FrameworkID the producer is generating a bundle for.
//
// # Outputs
//
//   - FrameworkBundleEntry: bytes + metadata as described above.
//   - error: ErrUnknownVersion if id has no Latest entry; the
//     wrapped LoadFromEmbedded error if the embedded slice is
//     somehow corrupt (should not happen — embed.FS is build-time
//     constant + self-attestation runs in LoadFromReader).
//
// # Example
//
//	entry, err := frameworks.PinForBundle(frameworks.SOC2_2017)
//	if errors.Is(err, frameworks.ErrUnknownVersion) {
//	    return fmt.Errorf("no Latest pin for %s; seed not registered", req.Framework)
//	}
//
// # Limitations
//
//   - Calls into LoadFromEmbedded which re-verifies the
//     self-attestation hash on every call. For a hot path this is a
//     SHA-512 over ~5 KB per call; negligible but worth knowing.
//   - The function does NOT cache. Each call re-reads from embed.FS,
//     re-canonicalizes, re-hashes. Stateless by design — eliminates
//     mutation-of-cached-state hazards in a concurrent finalize
//     pipeline.
//
// # Assumptions
//
//   - Latest is treated as read-only by the caller (see registry.go
//     doc). PinForBundle reads it; nothing else.
//   - The embedded controls.json was generated by
//     cmd/frameworks-seedgen and therefore satisfies the
//     self-attestation contract. If a developer hand-edits a
//     controls.json, LoadFromEmbedded fails closed and PinForBundle
//     returns the wrapped error.
func PinForBundle(id FrameworkID) (FrameworkBundleEntry, error) {
	vid, ok := Latest[id]
	if !ok {
		return FrameworkBundleEntry{}, fmt.Errorf("%w: no Latest pin for FrameworkID %q", ErrUnknownVersion, id)
	}

	f, err := LoadFromEmbedded(vid)
	if err != nil {
		return FrameworkBundleEntry{}, fmt.Errorf("load embedded %q: %w", vid, err)
	}

	contents, err := CanonicalJSONOnWire(f)
	if err != nil {
		return FrameworkBundleEntry{}, fmt.Errorf("canonical on-wire bytes for %q: %w", vid, err)
	}

	sum := sha512.Sum512(contents)
	return FrameworkBundleEntry{
		Path:      bundlePathFor(vid),
		Contents:  contents,
		SHA512Hex: hex.EncodeToString(sum[:]),
		SizeBytes: int64(len(contents)),
		VersionID: vid,
	}, nil
}

// bundlePathFor returns the conventional in-bundle path for a
// framework version's controls.json.
//
// # Description
//
// The path is "frameworks/<version_id>/controls.json" where
// <version_id> is the full "<framework_id>@<YYYYMMDD>" string. This
// mirrors the compliance_bundle_format_spec.md §"Bundle path
// convention" (CV-02 amendment).
//
// # Limitations
//
//   - The path contains "@" which is a valid filename character on
//     POSIX and ZIP but may surprise Windows extractors. ZIP central
//     directory entries store the path verbatim; consumers that
//     extract to disk on Windows should expect "@" in directory names.
func bundlePathFor(vid VersionID) string {
	return "frameworks/" + string(vid) + "/controls.json"
}
