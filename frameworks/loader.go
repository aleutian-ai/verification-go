// DomainPrefix is the domain-separation tag for the framework
// self-attestation hash, per the codebase-wide convention documented
// in sdk_domain_prefix_registry. Hash input is:
//
//	DomainPrefix || canonicalJSON(framework_with_hash_field_blanked)
//
// The prefix prevents cross-protocol replay against any other SHA-512
// over JSON bytes in the system (manifest_root, file content hashes,
// chain content hashes). Locked 2026-05-31 via CV-01 post-review fixes.
const DomainPrefix = "aleutian.framework_controls.v1:"

// MaxControlsJSONBytes is the hard cap on a single controls.json read
// by LoadFromReader. Real controls.json files are KB-scale; this 1 MiB
// cap is a defense-in-depth against malicious bundles supplying
// multi-GB JSON to exhaust verifier memory.
const MaxControlsJSONBytes = 1 << 20

// Sentinel errors returned by the loader. Callers should use
// errors.Is to dispatch; the wrapped error carries context (which
// version, which field, which status string).
var (
	// ErrAttestationMismatch indicates the SHA-512 hash recorded in
	// controls_sha512_hex does not match the canonical bytes of the
	// rest of the object. Bundle verification MUST fail closed on this
	// error — the controls.json has been tampered with or was
	// generated by a producer with a different canonicalization rule.
	ErrAttestationMismatch = errors.New("frameworks: controls_sha512_hex does not match canonical bytes")

	// ErrUnknownVersion indicates LoadFromEmbedded was asked for a
	// VersionID that is not compiled into this SDK build. Verifiers
	// should treat this as "your SDK is older than this bundle —
	// upgrade" rather than as a verification failure.
	ErrUnknownVersion = errors.New("frameworks: version not embedded in this SDK build")

	// ErrUnknownStatus indicates a Control carries a status value that
	// is not one of operating | designed | roadmap. Fail-closed
	// forward-compatibility: an older SDK reading a newer bundle's
	// future status refuses to load rather than silently
	// miscategorizing.
	ErrUnknownStatus = errors.New("frameworks: control status is not one of operating|designed|roadmap")

	// ErrMalformedJSON wraps any JSON syntactic or structural error
	// surfaced during load.
	ErrMalformedJSON = errors.New("frameworks: controls.json is malformed")

	// ErrFrameworkVersionMismatch indicates the framework_version
	// pinned in a bundle's manifest does not equal the version_id
	// inside the framework's controls.json. Declared here for CV-05
	// (SDK verify step-9 cross-check) so all three SDKs converge on
	// the same sentinel. Loader itself does not raise this error;
	// CV-05 raises it after a successful Load.
	ErrFrameworkVersionMismatch = errors.New("frameworks: manifest.framework_version != controls.json version_id")

	// ErrSizeExceeded indicates the input exceeded MaxControlsJSONBytes
	// before EOF. A well-formed controls.json is KB-scale; anything
	// larger is rejected as a defense against memory-exhaustion bombs.
	ErrSizeExceeded = errors.New("frameworks: controls.json exceeds size cap")

	// ErrHashFormat indicates controls_sha512_hex is not 128
	// lowercase hex characters. Producers MUST emit lowercase; older
	// uppercase-emitting producers would silently fork from
	// case-sensitive byte-identity in Python/JS verifiers.
	ErrHashFormat = errors.New("frameworks: controls_sha512_hex must be 128 lowercase hex characters")

	// ErrFrameworkMissing indicates the expected
	// frameworks/<version>/controls.json path is absent from the
	// bundle filesystem. CV-05 raises this when the manifest declares
	// a framework_version but the bundle does not actually ship the
	// referenced controls.json file.
	ErrFrameworkMissing = errors.New("frameworks: bundle does not contain frameworks/<version>/controls.json")
)

// LoadFromReader parses canonical JSON from r and returns the
// Framework after verifying its self-attestation hash and that every
// control carries a known status.
//
// # Description
//
// The self-attestation contract is: ControlsSHA512Hex is the
// lowercase-hex SHA-512 of
//
//	DomainPrefix || canonicalJSON(framework_with_hash_field_blanked)
//
// This covers Controls, ControlsOutOfScope, AleutianSnapshotAt, and
// every other top-level field, so a producer cannot tamper with the
// scope (e.g. quietly drop a control from ControlsOutOfScope) without
// invalidating the hash.
//
// # Inputs
//
//   - r: an io.Reader streaming the bytes of a controls.json file.
//     Capped at MaxControlsJSONBytes (1 MiB).
//
// # Outputs
//
//   - Framework: the parsed and verified framework.
//   - error: ErrMalformedJSON if the bytes aren't valid JSON;
//     ErrSizeExceeded if input exceeds the cap; ErrHashFormat if the
//     recorded hash is not 128 lowercase hex; ErrUnknownStatus if any
//     control's status is not one of the locked values;
//     ErrAttestationMismatch if the recorded hash doesn't match the
//     canonical bytes.
//
// # Example
//
//	f, err := frameworks.LoadFromReader(bundleEntry)
//	if errors.Is(err, frameworks.ErrAttestationMismatch) {
//	    return fmt.Errorf("bundle tampered: %w", err)
//	}
//
// # Limitations
//
//   - Uses canonicalJSON (hand-rolled, see canonical_json.go) rather
//     than encoding/json for the hash input. encoding/json's HTML
//     escaping and struct-field-declaration ordering would diverge
//     from Python/JS sibling SDKs over a 7-year retention horizon.
//
// # Assumptions
//
//   - Hash comparison is constant-time via crypto/subtle to prevent
//     timing-leak inference against a (very low-value) on-disk hash.
//     Cost is negligible; consistency with the codebase's discipline.
func LoadFromReader(r io.Reader) (Framework, error) {
	limited := io.LimitReader(r, int64(MaxControlsJSONBytes)+1)
	raw, err := io.ReadAll(limited)
	if err != nil {
		return Framework{}, fmt.Errorf("frameworks: read controls.json: %w", err)
	}
	if len(raw) > MaxControlsJSONBytes {
		return Framework{}, fmt.Errorf("%w: read >%d bytes", ErrSizeExceeded, MaxControlsJSONBytes)
	}

	var f Framework
	dec := json.NewDecoder(strings.NewReader(string(raw)))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&f); err != nil {
		return Framework{}, fmt.Errorf("%w: %v", ErrMalformedJSON, err)
	}

	if !isLowercaseHex128(f.ControlsSHA512Hex) {
		return Framework{}, fmt.Errorf("%w: got %q", ErrHashFormat, f.ControlsSHA512Hex)
	}

	for i, c := range f.Controls {
		if !c.Status.IsKnown() {
			return Framework{}, fmt.Errorf("%w: controls[%d].status=%q", ErrUnknownStatus, i, c.Status)
		}
	}

	expected, err := CanonicalBytesForHashing(f)
	if err != nil {
		return Framework{}, fmt.Errorf("frameworks: canonicalize for hashing: %w", err)
	}
	sum := sha512.Sum512(expected)
	gotHex := hex.EncodeToString(sum[:])
	if subtle.ConstantTimeCompare([]byte(gotHex), []byte(f.ControlsSHA512Hex)) != 1 {
		return Framework{}, fmt.Errorf("%w: expected=%s recorded=%s", ErrAttestationMismatch, gotHex, f.ControlsSHA512Hex)
	}

	return f, nil
}

// LoadFromEmbedded returns the embedded Framework for v.
//
// # Description
//
// Looks up the embedded controls.json at the conventional path
// "<framework_id>/v_<YYYYMMDD>/controls.json" inside the package's
// embed.FS. Returns ErrUnknownVersion if no such file is embedded in
// this SDK build.
//
// # Inputs
//
//   - v: a VersionID of the form "<framework_id>@<YYYYMMDD>".
//
// # Outputs
//
//   - Framework: the loaded and verified framework.
//   - error: ErrUnknownVersion if v is not embedded; the wrapped
//     LoadFromReader error otherwise.
//
// # Limitations
//
//   - CV-01 ships embedded as a zero-value embed.FS — every call
//     returns ErrUnknownVersion. Seed ticket 03 adds the //go:embed
//     directive that populates it.
//
// # Assumptions
//
//   - VersionID format is "<framework_id>@<YYYYMMDD>" with exactly one
//     "@". Malformed v values return ErrUnknownVersion (not a parse
//     error) because the contract is "is this version available."
func LoadFromEmbedded(v VersionID) (Framework, error) {
	at := strings.IndexByte(string(v), '@')
	if at < 1 || at == len(v)-1 {
		return Framework{}, fmt.Errorf("%w: %q", ErrUnknownVersion, v)
	}
	frameworkID := FrameworkID(v[:at])
	dateSuffix := string(v[at+1:])

	// Whitelist check: only IDs that appear as a constant in
	// framework_ids.go are loadable. This means a stray directory
	// matching the embed glob (e.g. a testdata dir under
	// frameworks/) cannot be served as a "framework" by accident.
	if !isRegisteredFrameworkID(frameworkID) {
		return Framework{}, fmt.Errorf("%w: %q", ErrUnknownVersion, v)
	}

	embedPath := path.Join(string(frameworkID), "v_"+dateSuffix, "controls.json")

	file, err := embedded.Open(embedPath)
	if err != nil {
		return Framework{}, fmt.Errorf("%w: %q", ErrUnknownVersion, v)
	}
	defer func() { _ = file.Close() }()

	return LoadFromReader(file)
}

// isRegisteredFrameworkID reports whether id is one of the typed
// FrameworkID constants declared in framework_ids.go. Used as a
// belt-and-suspenders check against an over-broad embed glob picking
// up unexpected directories.
func isRegisteredFrameworkID(id FrameworkID) bool {
	switch id {
	case SOC2_2017,
		GDPR,
		EU_AI_ACT,
		HIPAA,
		NIST_CSF_V1_1,
		NIST_800_53,
		ISO_27001_2022,
		PCI_DSS_V4,
		CCPA_CPRA:
		return true
	}
	return false
}

// CanonicalJSONOnWire returns the canonical JSON bytes of f exactly
// as they should appear in a controls.json file on disk: hash field
// populated, no domain prefix.
//
// # Description
//
// Producers (cmd/frameworks-seedgen) call this after computing the
// SHA-512 over CanonicalBytesForHashing and setting
// f.ControlsSHA512Hex. The returned bytes are the byte-stable on-wire
// form: emitting them and re-loading via LoadFromReader is a no-op.
//
// # Inputs
//
//   - f: the Framework, with ControlsSHA512Hex already populated.
//
// # Outputs
//
//   - []byte: the canonical JSON encoding of f, no domain prefix.
//   - error: any encoding error from canonicalJSON.
//
// # Limitations
//
//   - This function does NOT verify the hash matches the canonical
//     content. Callers compute and inject the hash themselves; the
//     loader is the verification point.
func CanonicalJSONOnWire(f Framework) ([]byte, error) {
	return canonicalJSON(f)
}

// CanonicalBytesForHashing returns
//
//	DomainPrefix || canonicalJSON(f_with_ControlsSHA512Hex_blanked)
//
// — the exact byte sequence fed to SHA-512 for the self-attestation.
//
// # Description
//
// Producers call this to compute the SHA-512 that goes back into
// ControlsSHA512Hex before serializing the controls.json to disk.
// Verifiers call LoadFromReader, which calls this internally. The
// domain prefix prevents the framework hash from being cross-protocol
// confused with any other SHA-512 in the bundle.
//
// # Inputs
//
//   - f: the Framework to canonicalize.
//
// # Outputs
//
//   - []byte: DomainPrefix concatenated with the canonical JSON
//     encoding of f, with controls_sha512_hex blanked.
//   - error: any encoding error from canonicalJSON (none expected for
//     well-typed input).
func CanonicalBytesForHashing(f Framework) ([]byte, error) {
	clone := f
	clone.ControlsSHA512Hex = ""
	canonical, err := canonicalJSON(clone)
	if err != nil {
		return nil, err
	}
	out := make([]byte, 0, len(DomainPrefix)+len(canonical))
	out = append(out, DomainPrefix...)
	out = append(out, canonical...)
	return out, nil
}

// isLowercaseHex128 reports whether s is exactly 128 characters of
// lowercase hex (0-9, a-f).
//
// # Description
//
// SHA-512 hex is 128 chars. Producer convention is lowercase across
// every SHA in the Aleutian codebase (Python's hashlib.sha512().hexdigest()
// and JS's crypto.subtle returning lowercase by default). Rejecting
// uppercase at parse time prevents the latent fork where a Go-only
// uppercase-emitting producer would pass Go verification but fail
// byte-identity in Python/JS sibling SDKs.
func isLowercaseHex128(s string) bool {
	if len(s) != 128 {
		return false
	}
	for i := 0; i < len(s); i++ {
		c := s[i]
		if !((c >= '0' && c <= '9') || (c >= 'a' && c <= 'f')) {
			return false
		}
	}
	return true
}
